export function createInitialSpreadsheet(): SpreadsheetData {
  const rawRows: string[][] = [
    [...SAMPLE_COLUMNS],
    ...SAMPLE_ENTRIES.map((row) => SAMPLE_COLUMNS.map((col) => row[col as keyof typeof row] ?? '')),
  ];

  const selection = {
    startRow: 0,
    startCol: 0,
    endRow: rawRows.length - 1,
    endCol: SAMPLE_COLUMNS.length - 1,
    useFirstRowAsHeader: true,
    mode: 'rows' as const,
    excludedRows: [],
    excludedCells: [],
  };

  const entries = SAMPLE_ENTRIES.map((row) => ({ ...row }));

  return {
    fileName: 'annual-charity-raffle.xlsx',
    sheetNames: ['Participants'],
    activeSheet: 'Participants',
    rawRows,
    selection,
    columns: [...SAMPLE_COLUMNS],
    entries,
    workbookSheets: {
      Participants: {
        rawRows: rawRows.map((r) => [...r]),
        selection: { ...selection },
        columns: [...SAMPLE_COLUMNS],
        entries: entries.map((r) => ({ ...r })),
      },
    },
  };
}

